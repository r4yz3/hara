<#
.SYNOPSIS
  Production-like rehearsal stack (backlog E-05). See docs/operations/deploy.md.
.EXAMPLE
  .\infra\scripts\rehearsal.ps1 env
  .\infra\scripts\rehearsal.ps1 build -Release n
  .\infra\scripts\rehearsal.ps1 up -Release n
  .\infra\scripts\rehearsal.ps1 migrate -Release n
  .\infra\scripts\rehearsal.ps1 backup
  .\infra\scripts\rehearsal.ps1 down
#>
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [ValidateSet('env', 'build', 'up', 'migrate', 'rollback-migration', 'status', 'backup', 'restore', 'down', 'destroy')]
    [string]$Task,
    # Image tag to build or run, e.g. a commit id. Letters, digits, dot, dash, underscore.
    [ValidatePattern('^[A-Za-z0-9._-]{1,64}$')]
    [string]$Release,
    [ValidateRange(1, 50)]
    [int]$Steps = 1
)

$ErrorActionPreference = 'Stop'
$Root = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$Dir = Join-Path $Root 'infra\rehearsal'
$EnvFile = Join-Path $Dir '.env'
$Backups = Join-Path $Root 'infra\backups\rehearsal'
$Compose = @('compose', '-f', (Join-Path $Dir 'compose.yaml'), '--env-file', $EnvFile)

function Invoke-Step([string]$Name, [scriptblock]$Body) {
    Write-Host "==> $Name"
    # Exit code decides; see the note in dev.ps1.
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $Body 2>&1 | ForEach-Object {
            if ($_ -is [System.Management.Automation.ErrorRecord]) { Write-Host $_.Exception.Message } else { $_ }
        }
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    if ($code -ne 0) { throw "FAILED: $Name (exit $code)" }
}

function New-Secret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    return $buffer
}

function Require-Release {
    if (-not $Release) { throw 'Pass -Release <tag>.' }
    $env:RELEASE = $Release
}

function Require-Env {
    if (-not (Test-Path $EnvFile)) { throw 'No infra\rehearsal\.env. Run: .\infra\scripts\rehearsal.ps1 env' }
}

# compose.yaml requires RELEASE to name images. Tasks that only touch the
# database (backup, restore, down) never start an image, so any value will do.
if (-not $Release -and -not $env:RELEASE) { $env:RELEASE = 'none' }

Push-Location $Root
try {
    switch ($Task) {
        'env' {
            if (Test-Path $EnvFile) { throw 'infra\rehearsal\.env already exists. Delete it first to make a new one (the old database password will stop working).' }
            $appKey = 'base64:' + [Convert]::ToBase64String((New-Secret 32))
            # Hex keeps the password free of characters that need quoting anywhere.
            $dbPassword = -join ((New-Secret 24) | ForEach-Object { $_.ToString('x2') })
            # Staging settings that satisfy ProductionGuard. Hosts use the reserved
            # .example domain: nothing here points at a real site.
            @"
# Generated by rehearsal.ps1 env on $((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')). Git-ignored. Rehearsal only.
APP_ENV=staging
APP_DEBUG=false
APP_URL=https://api.rehearsal.example
APP_KEY=$appKey
DB_CONNECTION=pgsql
DB_HOST=postgres
DB_PORT=5432
DB_DATABASE=food_delivery
DB_USERNAME=food_delivery
DB_PASSWORD=$dbPassword
REDIS_HOST=redis
REDIS_PORT=6379
CACHE_STORE=redis
QUEUE_CONNECTION=redis
SESSION_DRIVER=redis
SESSION_SECURE_COOKIE=true
HASH_DRIVER=argon2id
CUSTOMER_APP_URL=https://customer.rehearsal.example
MERCHANT_APP_URL=https://merchant.rehearsal.example
ADMIN_APP_URL=https://admin.rehearsal.example
LOG_CHANNEL=stack
LOG_STACK=json
MAIL_MAILER=log
DEFAULT_CURRENCY=PHP
BOOST_BROWSER_LOGS_WATCHER=false
"@ | Set-Content -Encoding ascii $EnvFile
            Write-Host 'Wrote infra\rehearsal\.env with fresh random secrets.'
        }
        'build' {
            Require-Release
            Invoke-Step "build api:$Release" { docker build -f infra/docker/prod/api.Dockerfile --target api -t "food-delivery-api:$Release" . }
            Invoke-Step "build web:$Release" { docker build -f infra/docker/prod/api.Dockerfile --target web -t "food-delivery-web:$Release" . }
        }
        'up' {
            Require-Env; Require-Release
            Invoke-Step "run release $Release" { docker @Compose up -d --wait }
        }
        'migrate' {
            Require-Env; Require-Release
            Invoke-Step 'migrate' { docker @Compose run --rm --no-deps api php artisan migrate --force --no-ansi }
        }
        'rollback-migration' {
            Require-Env; Require-Release
            # Run with the release that ADDED the migrations: only it has their down().
            Invoke-Step "roll back $Steps migration(s)" { docker @Compose run --rm --no-deps api php artisan migrate:rollback --step=$Steps --force --no-ansi }
        }
        'status' {
            Require-Env; Require-Release
            Invoke-Step 'migration status' { docker @Compose run --rm --no-deps api php artisan migrate:status --no-ansi }
        }
        'backup' {
            Require-Env
            New-Item -ItemType Directory -Force $Backups | Out-Null
            $file = Join-Path $Backups ("rehearsal-{0}.dump" -f (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss'))
            Invoke-Step 'dump database' { docker @Compose exec -T postgres sh -c 'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc -f /tmp/rehearsal.dump' }
            Invoke-Step 'copy backup out' { docker @Compose cp postgres:/tmp/rehearsal.dump $file }
            Invoke-Step 'remove copy in container' { docker @Compose exec -T postgres rm -f /tmp/rehearsal.dump }
            (Get-FileHash -Algorithm SHA256 $file).Hash.ToLower() | Set-Content -Encoding ascii "$file.sha256"
            Write-Host "Backup written to $file"
        }
        'restore' {
            Require-Env
            # Replaces the rehearsal database with the newest rehearsal backup. Rehearsal only.
            $latest = Get-ChildItem $Backups -Filter '*.dump' -ErrorAction SilentlyContinue | Sort-Object Name | Select-Object -Last 1
            if (-not $latest) { throw 'No rehearsal backup found.' }
            $expected = (Get-Content "$($latest.FullName).sha256" -TotalCount 1).Trim()
            if ((Get-FileHash -Algorithm SHA256 $latest.FullName).Hash.ToLower() -ne $expected) { throw 'Backup checksum does not match; not restoring.' }
            Write-Host "Restoring $($latest.Name)"
            Invoke-Step 'copy backup in' { docker @Compose cp $latest.FullName postgres:/tmp/rehearsal.dump }
            # Drop and recreate the whole database rather than `pg_restore --clean`:
            # --clean only drops objects that are in the backup, so a table a later
            # release created would survive while the migration ledger says it was
            # never made, and the next deploy of that release would fail on it.
            # --force ends the API's open connections; stop or pause traffic first.
            Invoke-Step 'replace database' { docker @Compose exec -T postgres sh -c 'dropdb -U "$POSTGRES_USER" --force "$POSTGRES_DB" && createdb -U "$POSTGRES_USER" -O "$POSTGRES_USER" "$POSTGRES_DB"' }
            Invoke-Step 'restore' { docker @Compose exec -T postgres sh -c 'pg_restore -U "$POSTGRES_USER" -d "$POSTGRES_DB" --single-transaction --no-owner --exit-on-error /tmp/rehearsal.dump && rm -f /tmp/rehearsal.dump' }
        }
        'down' {
            Require-Env
            # Keeps the rehearsal database volume.
            Invoke-Step 'stop rehearsal stack' { docker @Compose down }
        }
        'destroy' {
            Require-Env
            # Deletes the rehearsal database volume. Never touches the development stack.
            Invoke-Step 'remove rehearsal stack and its data' { docker @Compose down -v }
        }
    }
} finally {
    Pop-Location
}
