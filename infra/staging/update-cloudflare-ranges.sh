#!/usr/bin/env bash
# Regenerates nginx/conf.d/cloudflare.conf from Cloudflare's published ranges
# (https://www.cloudflare.com/ips-v4 and /ips-v6). The file does two jobs:
#   1. set_real_ip_from: believe CF-Connecting-IP only when the TCP peer is Cloudflare.
#   2. geo $hara_trusted_peer: nginx refuses (444) any peer that is not Cloudflare,
#      a second layer behind the firewall (cloudflare-only-firewall.sh).
# The Docker bridge gateway is added to both: connections from the host itself
# (smoke tests with curl) and, when Docker's userland proxy carries IPv6, from
# the internet, arrive from that address. Loopback is trusted for the
# container's own health check. Keep it in step with compose.yaml.
#
# No secret is involved; the output is committed so a deploy needs no network
# fetch. Re-run it, review the diff, and reload nginx when Cloudflare changes
# its ranges (rare):
#   infra/staging/update-cloudflare-ranges.sh
#   docker compose exec edge nginx -s reload
set -euo pipefail

GATEWAY="172.31.77.1"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-$HERE/nginx/conf.d/cloudflare.conf}"

fetch() {
  local url="$1" pattern="$2" body
  body="$(curl --fail --silent --show-error --max-time 20 --proto '=https' --tlsv1.2 "$url")"
  # Refuse anything that is not a plain list of CIDR ranges.
  [ -n "$body" ] || { echo "Empty answer from $url; not writing anything." >&2; exit 1; }
  if printf '%s\n' "$body" | grep -Ev "$pattern" | grep -q .; then
    echo "Unexpected content from $url; not writing anything." >&2
    exit 1
  fi
  printf '%s\n' "$body"
}

V4="$(fetch https://www.cloudflare.com/ips-v4 '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$')"
V6="$(fetch https://www.cloudflare.com/ips-v6 '^[0-9a-fA-F:]+/[0-9]{1,3}$')"
[ "$(printf '%s\n' "$V4" | wc -l)" -ge 5 ] || { echo "Too few IPv4 ranges; not writing anything." >&2; exit 1; }
[ "$(printf '%s\n' "$V6" | wc -l)" -ge 3 ] || { echo "Too few IPv6 ranges; not writing anything." >&2; exit 1; }

TMP="$(mktemp)"
{
  echo "# Generated by update-cloudflare-ranges.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit by hand."
  echo "# Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6"
  echo
  echo "# Believe CF-Connecting-IP only from these peers."
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive off;"
  printf '%s\n' "$V4" "$V6" | sed 's/^/set_real_ip_from /; s/$/;/'
  echo
  echo "# 1 for a peer allowed to talk to this server at all."
  echo "geo \$realip_remote_addr \$hara_trusted_peer {"
  echo "    default 0;"
  printf '%s\n' "$V4" "$V6" | sed 's/^/    /; s/$/ 1;/'
  echo "    $GATEWAY/32 1;"
  echo "    127.0.0.1/32 1;"
  echo "    ::1/128 1;"
  echo "}"
} > "$TMP"
mv "$TMP" "$OUT"
chmod 0644 "$OUT"
echo "Wrote $OUT"
