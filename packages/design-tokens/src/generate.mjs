import { contrastRatio } from "./contrast.mjs";
import { pairs, restricted, tokens } from "./tokens.mjs";

const block = (theme, indent) =>
  Object.entries(tokens[theme])
    .map(([name, value]) => `${indent}--${name}: ${value.toLowerCase()};`)
    .join("\n");

export function renderCss() {
  return `/* GENERATED from src/tokens.mjs. Do not edit; run the package's build script. */
:root {
${block("light", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root {
${block("dark", "    ")}
  }
}
`;
}

const dartName = (token) => token.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const dartClass = (name, theme) => {
  const lines = Object.entries(tokens[theme]).map(
    ([token, value]) => `  static const ${dartName(token)} = Color(0xFF${value.slice(1).toUpperCase()});`,
  );

  return [`abstract final class ${name} {`, ...lines, "}", ""].join("\n");
};

/** Colour constants for the Flutter rider app, from the same source as tokens.css. */
export function renderDart() {
  return `// GENERATED from packages/design-tokens/src/tokens.mjs. Do not edit;
// run the design-tokens build script. Approved foreground/background pairs
// are listed in docs/ux/contrast-report.md.

import 'dart:ui';

${dartClass("LightTokens", "light")}
${dartClass("DarkTokens", "dark")}`;
}

export function measure() {
  return ["light", "dark"].flatMap((theme) =>
    pairs.map((pair) => {
      const ratio = contrastRatio(tokens[theme][pair.foreground], tokens[theme][pair.background]);
      return { theme, ...pair, ratio, pass: ratio >= pair.min };
    }),
  );
}

export function renderReport() {
  const rows = measure()
    .map((r) => `| ${r.theme} | \`${r.foreground}\` | \`${r.background}\` | ${r.use} | ${r.ratio.toFixed(2)} | ${r.min} | ${r.pass ? "pass" : "FAIL"} |`)
    .join("\n");

  const limits = restricted
    .map((r) => {
      const light = contrastRatio(tokens.light[r.token], tokens.light.surface).toFixed(2);
      const dark = contrastRatio(tokens.dark[r.token], tokens.dark.surface).toFixed(2);
      return `| \`${r.token}\` | ${light} | ${dark} | ${r.rule} |`;
    })
    .join("\n");

  return `# Colour contrast report

GENERATED by \`packages/design-tokens\` from \`src/tokens.mjs\`. Do not edit by hand.

Ratios are WCAG 2.x contrast ratios for opaque colours. Thresholds: 4.5 for normal text (success criterion 1.4.3), 3 for control outlines and focus rings (1.4.11). This covers colour pairs only; it is not a full accessibility audit, and it says nothing about map tiles, images, disabled states or text over gradients.

## Approved pairs

| Theme | Foreground | Background | Use | Ratio | Required | Result |
|---|---|---|---|---:|---:|---|
${rows}

Only the pairs above are approved. Any other combination is unmeasured.

## Restricted tokens

Ratio shown is against \`surface\`.

| Token | Light | Dark | Rule |
|---|---:|---:|---|
${limits}
`;
}
